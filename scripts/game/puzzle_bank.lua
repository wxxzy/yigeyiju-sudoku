-- 已解析的题目缓存（每档一份 table of puzzle）
local cache_ = {}
-- 每档上一次抽到的下标，避免连续重复同一题
local lastPick_ = {}

local function parse(str)
    local puzzle = {}
    for i = 1, 81 do
        puzzle[i] = tonumber(str:sub(i, i)) or 0
    end
    return puzzle
end

local function tierOf(difficulty)
    return Bank.DATA[difficulty]
end

--- 某档有多少题
function Bank.count(difficulty)
    local list = tierOf(difficulty)
    return list and #list or 0
end

--- 按下标取题（每日一题用：同一天必须取到同一题）
---@param difficulty string
---@param index integer 1..count
---@return table|nil puzzle
function Bank.pickAt(difficulty, index)
    local strings = tierOf(difficulty)
    if not strings or #strings == 0 then
        return nil
    end
    local n = #strings
    local i = ((math.floor(index or 1) - 1) % n) + 1

    cache_[difficulty] = cache_[difficulty] or {}
    local parsed = cache_[difficulty]
    if not parsed[i] then
        parsed[i] = parse(strings[i])
    end

    local copy = {}
    for k = 1, 81 do
        copy[k] = parsed[i][k]
    end
    return copy
end

--- 取一题（随机，避免与上一次重复）
---@return table|nil puzzle 0 表示空格
function Bank.pick(difficulty)
    local strings = tierOf(difficulty)
    if not strings or #strings == 0 then
        return nil
    end

    cache_[difficulty] = cache_[difficulty] or {}
    local parsed = cache_[difficulty]

    local idx = math.random(#strings)
    if #strings > 1 and idx == lastPick_[difficulty] then
        idx = (idx % #strings) + 1
    end
    lastPick_[difficulty] = idx

    if not parsed[idx] then
        parsed[idx] = parse(strings[idx])
    end

    -- 返回副本，避免调用方改到缓存
    local copy = {}
    for i = 1, 81 do
        copy[i] = parsed[idx][i]
    end
    return copy
end

return Bank
